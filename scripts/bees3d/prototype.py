"""Build the isolated Zhuzha style experiment; does not overwrite production art.

python3 scripts/bees3d/prototype.py jobs ../bee-prototype/renders > ../bee-prototype/jobs.json
blender -b -P scripts/bees3d/render_lowpoly.py -- ../bee-prototype/jobs.json
python3 scripts/bees3d/prototype.py pack ../bee-prototype/renders
"""
import argparse
import json
from pathlib import Path

VIEWS = (0, 16, 32, 47, 62)
SKINS = ("scarf", "bow", "glasses", "backpack", "wreath", "beret", "headphones", "halo")
ROOT = Path(__file__).resolve().parents[2]


def jobs(directory):
    passes = ["body", "eyes", "wingL", "wingR", "goldL", "goldR", "crown"]
    passes += ["skin_" + skin for skin in SKINS]
    result = []
    for view in VIEWS:
        result.append({"species": "zhuzha", "view": view, "size": 384,
                       "out_dir": str(directory), "passes": passes + ["full"],
                       "samples": 96, "style": "honey-soft",
                       **({"save_blend": str(directory.parent / "zhuzha.blend")} if view == 32 else {})})
    print(json.dumps(result))


def pack(directory):
    from PIL import Image
    destination = ROOT / "assets/art/bees-prototype"
    destination.mkdir(parents=True, exist_ok=True)
    lines = ['/* Generated by scripts/bees3d/prototype.py; isolated Zhuzha experiment. */',
             'import type { BeeView, SharedView } from "./beeArt";']
    layers = {}
    metadata = {}
    for view in VIEWS:
        tag = f"zhuzha_{view}"
        meta = json.loads((directory / (tag + ".json")).read_text())
        metadata[view] = meta
        for part in ["body", "eyes", "wingL", "wingR", "goldL", "goldR", "crown"] + ["skin_" + s for s in SKINS]:
            source = directory / f"{tag}_{part}.png"
            im = Image.open(source).convert("RGBA")
            if im.size != (meta["size"], meta["size"]):
                raise ValueError(f"Frame mismatch: {source}")
            bounds = im.getchannel("A").point(lambda value: 255 if value > 3 else 0).getbbox()
            if bounds is None:
                raise ValueError(f"Empty layer: {source}")
            size = meta["size"]
            x0, y0, x1, y1 = bounds
            x0, y0, x1, y1 = max(0, x0 - 1), max(0, y0 - 1), min(size, x1 + 1), min(size, y1 + 1)
            name = f"{tag}_{part}.webp"
            im.crop((x0, y0, x1, y1)).save(destination / name, "WEBP", quality=90, method=6)
            rect = [round(v / size, 5) for v in (x0, y0, x1 - x0, y1 - y0)]
            key = f"P{len(layers)}"
            lines.append(f'const {key} = require("../../assets/art/bees-prototype/{name}");')
            layers[view, part] = f"[{key}, {json.dumps(rect)}]"
    def point(view, key):
        meta = metadata[view]
        return json.dumps([round(v / meta["size"], 5) for v in meta[key]])
    lines.append("export const PROTOTYPE_BEE_VIEWS: BeeView[] = [")
    for view in VIEWS:
        lines.append(f"  {{ yaw: {view}, body: {layers[view, 'body']}, eyes: {layers[view, 'eyes']}, "
                     f"pivotL: {point(view, 'pivotL')}, pivotR: {point(view, 'pivotR')} }},")
    lines.append("];")
    lines.append("export const PROTOTYPE_SHARED_VIEWS: Record<number, SharedView> = {")
    for view in VIEWS:
        parts = ", ".join(f"{part}: {layers[view, part]}" for part in ("wingL", "wingR", "goldL", "goldR", "crown"))
        skins = ", ".join(f"{skin}: {layers[view, 'skin_' + skin]}" for skin in SKINS)
        lines.append(f"  {view}: {{ {parts}, skins: {{ {skins} }}, pivotL: {point(view, 'pivotL')}, pivotR: {point(view, 'pivotR')} }},")
    lines.append("};")
    (ROOT / "src/ui/beePrototypeArt.ts").write_text("\n".join(lines) + "\n")
    print(f"Packed {len(layers)} non-empty layers; {sum(p.stat().st_size for p in destination.glob('*.webp')):,} bytes")


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("action", choices=("jobs", "pack"))
    parser.add_argument("directory", type=Path)
    args = parser.parse_args()
    directory = args.directory.resolve()
    if args.action == "jobs":
        jobs(directory)
    else:
        pack(directory)
