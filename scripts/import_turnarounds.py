"""Bake design/2d/all-species-accessories-v1 frames into small webp + src/ui/turnArt.ts.
small: 144px, 5 directions; large: 320px, front + q3-front. Items: base, crown + 7 skins (no headphones)."""
from PIL import Image; import os, json
SRC = "design/2d/all-species-accessories-v1"; OUT = "assets/art/turn"
BEES = [s["id"] for s in json.load(open(f"{SRC}/manifest.json"))["species"]]
ITEMS = {"base": None, "crown": "crown", "scarf": "scarf", "bow": "bow", "glasses": "glasses", "backpack": "bag", "wreath": "wreath", "beret": "beret", "halo": "halo"}
SMALL = ["front", "q3-front", "q3-front-left", "side", "side-left"]; LARGE = ["front", "q3-front"]
CROP = (26, 26, 486, 486)
lines = ["// generated by scripts/import_turnarounds.py — do not edit", "/* eslint-disable */", "export const TURN: Record<string, Record<string, Record<string, any>>> = {"]
for b in BEES:
    lines.append(f'  "{b}": {{')
    for it, fn in ITEMS.items():
        lines.append(f'    "{it}": {{')
        for size, dirs in ((144, SMALL), (320, LARGE)):
            for d in dirs:
                src = f"{SRC}/{b}/{d}-base-view.png" if fn is None else f"{SRC}/{b}/{fn}-{d}-view.png"
                if not os.path.exists(src): continue
                os.makedirs(f"{OUT}/{b}", exist_ok=True)
                o = f"{OUT}/{b}/{it}_{d}_{size}.webp"
                Image.open(src).convert("RGBA").crop(CROP).resize((size, size), Image.LANCZOS).save(o, "WEBP", quality=82, method=6)
                lines.append(f'      "{d}_{size}": require("../../{o}"),')
        lines.append("    },")
    lines.append("  },")
lines.append("};")
open("src/ui/turnArt.ts", "w").write("\n".join(lines) + "\n")
