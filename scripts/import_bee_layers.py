"""Reassemble approved bee art into shared body/wing/outfit WebP layers.
Flight frames: 288px (>=3x a 96px sprite). Static front portraits: 720px.
Bodies are resampled directly from full-size originals, not the old 112px pack.
Outfits remain independent layers so a body is not duplicated for every skin.
"""
import sys,os,json,shutil,numpy as np
sys.path.insert(0,os.path.dirname(__file__))
from PIL import Image,ImageOps
from bee_layers import layers,W
AS='design/2d/all-species-accessories-v1';OUT='assets/art/turn'
BEES=[s['id'] for s in json.load(open(f'{AS}/manifest.json'))['species']]
ITEMS={'crown':'crown','scarf':'scarf','bow':'bow','glasses':'glasses','backpack':'bag','wreath':'wreath','beret':'beret','halo':'halo'}
VIEWS={'front':('front',False),'q3-front':('q3-front',False),'side':('side',False),'q3-front-left':('q3-front',True),'side-left':('side',True)}
CROP=(26,26,486,486);SIZES={288:list(VIEWS),720:['front']}
def bbox(a):
    ys,xs=np.nonzero(a[...,3]>40);return xs.min(),ys.min(),xs.max(),ys.max()
shutil.rmtree(OUT,ignore_errors=True)
meta={};code=['// generated by scripts/import_bee_layers.py','export const TURN: Record<string, Record<string, Record<string, any>>> = {']
for bee in BEES:
    os.makedirs(f'{OUT}/{bee}',exist_ok=True);meta[bee]={};files={}
    def save(im,kind,d,n):
        p=f'{OUT}/{bee}/{kind}_{d}_{n}.webp';im.save(p,'WEBP',quality=90,method=6,exact=True)
        files.setdefault(kind,[]).append((f'{d}_{n}',p))
    for d,(view,mirror) in VIEWS.items():
        ly=layers(bee,view);comp=Image.new('RGBA',(W,W))
        for wing,_ in ly['wings']:comp.alpha_composite(wing)
        comp.alpha_composite(ly['body'])
        ref=np.array(Image.open(f'{AS}/{bee}/{d}-base-view.png').convert('RGBA'))
        x0,y0,x1,y1=bbox(np.array(comp));X0,Y0,X1,Y1=bbox(ref)
        scale=((X1-X0)/(x1-x0)+(Y1-Y0)/(y1-y0))/2
        fx0=W-1-x1 if mirror else x0
        def render(im,n):
            if mirror:im=ImageOps.mirror(im)
            step=(CROP[2]-CROP[0])/n
            return im.transform((n,n),Image.Transform.AFFINE,(step/scale,0,fx0+(CROP[0]-X0)/scale,0,step/scale,y0+(CROP[1]-Y0)/scale),resample=Image.Resampling.BICUBIC)
        piv={}
        for i,(wing,(px,py)) in enumerate(ly['wings']):
            qx=W-1-px if mirror else px;X=(qx-fx0)*scale+X0;Y=(py-y0)*scale+Y0
            piv[f'w{i}']=[round((X-CROP[0])/460,5),round((Y-CROP[1])/460,5),(-1 if i==0 else 1)*(-1 if mirror else 1)]
            for n,dirs in SIZES.items():
                if d in dirs and not mirror:save(render(wing,n),f'w{i}',d,n)
        meta[bee][d]=piv
        for n,dirs in SIZES.items():
            if d in dirs and not mirror:save(render(ly['body'],n),'base',d,n)
        for item,source in ITEMS.items():
            frame=np.array(Image.open(f'{AS}/{bee}/{source}-{d}-view.png').convert('RGBA'))
            diff=np.abs(frame.astype(int)-ref.astype(int)).max(-1)>16
            frame[~diff,3]=0;overlay=Image.fromarray(frame).crop(CROP)
            for n,dirs in SIZES.items():
                if d in dirs:save(overlay.resize((n,n),Image.Resampling.LANCZOS),item,d,n)
    # Share mirrored body/wing images; left outfits retain their own anatomical side.
    for kind in ['base','w0','w1']:
        for d in ['q3-front','side']:
            source=next(p for key,p in files[kind] if key==f'{d}_288')
            files[kind].append((f'{d}-left_288',source))
    code.append(f'  "{bee}": {{')
    for kind,entries in files.items():code.append(f'    "{kind}": {{'+', '.join(f'"{key}": require("../../{p}")' for key,p in entries)+'},')
    code.append('  },');print(bee,flush=True)
code+=['};','export const WING_ROOT: Record<string, Record<string, Record<string, [number, number, number]>>> = '+json.dumps(meta)+';']
open('src/ui/turnArt.ts','w').write('\n'.join(code)+'\n')
