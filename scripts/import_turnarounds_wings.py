"""v1.5: split wings out of the turnaround frames so they can flap.
Wing mask per bee+direction: colour-matched to the bee's own wing palette (bee-turnarounds wing sprites),
limited to a per-direction wing region learned from Boris+Nochka. Body frames = frame minus wing pixels
(outfit pixels over a wing are kept). Wings are behind the body, so removing them leaves no holes.
Output overwrites assets/art/turn/<bee>/<item>_<dir>_<size>.webp and adds wingL/wingR_<dir>_<size>.webp + src/ui/turnArt.ts."""
import sys, os, json; sys.path.insert(0, os.path.dirname(__file__))
from wingseg import *
SRC = S; OUT = "assets/art/turn"
BEES = [s["id"] for s in json.load(open(f"{SRC}/manifest.json"))["species"]]
ITEMS = {"base": None, "crown": "crown", "scarf": "scarf", "bow": "bow", "glasses": "glasses", "backpack": "bag", "wreath": "wreath", "beret": "beret", "halo": "halo"}
DIRS = ["front", "q3-front", "q3-front-left", "side", "side-left"]
CROP = (26, 26, 486, 486); SIZES = {112: DIRS, 240: ["front"]}
def save(arr, o, n):
    Image.fromarray(arr).crop(CROP).resize((n, n), Image.LANCZOS).save(o, "WEBP", quality=76, method=4)
meta = {}; lines = ["// generated by scripts/import_turnarounds_wings.py — do not edit", "/* eslint-disable */",
                    "export const TURN: Record<string, Record<string, Record<string, any>>> = {"]
for b in BEES:
    pal = palette(b); os.makedirs(f"{OUT}/{b}", exist_ok=True); meta[b] = {}
    masks = {}; bases = {}
    for d in DIRS:
        base = np.array(Image.open(f"{SRC}/{b}/{d}-base-view.png").convert("RGBA"))
        m = mask2(Image.fromarray(base), pal, d)
        m = nd.binary_dilation(m, iterations=2) & prior(d) & (base[..., 3] > 0)
        masks[d] = m; bases[d] = base
        ys, xs = np.nonzero(m); body = base[..., 3] > 0
        cx = np.nonzero(body & ~m)[1].mean() if (body & ~m).any() else 256
        side = {}
        for k, sel in (("L", xs < cx), ("R", xs >= cx)):
            w = np.zeros_like(base)
            if sel.sum() > 200:
                yy, xx = ys[sel], xs[sel]; w[yy, xx] = base[yy, xx]
                # wing root: the wing pixel nearest the body centre column, at the wing's lower half
                rx = xx.max() if k == "L" else xx.min(); ry = np.median(yy[np.abs(xx - rx) < 12])
                side[k] = [round((rx - CROP[0]) / (CROP[2] - CROP[0]), 3), round((ry - CROP[1]) / (CROP[3] - CROP[1]), 3)]
            for n, ds in SIZES.items():
                if d in ds and k in side: save(w, f"{OUT}/{b}/wing{k}_{d}_{n}.webp", n)
        meta[b][d] = side
    lines.append(f'  "{b}": {{')
    for it, fn in list(ITEMS.items()) + [("wingL", "wingL"), ("wingR", "wingR")]:
        lines.append(f'    "{it}": {{')
        for n, ds in SIZES.items():
            for d in ds:
                if it in ("wingL", "wingR"):
                    o = f"{OUT}/{b}/{it}_{d}_{n}.webp"
                    if os.path.exists(o): lines.append(f'      "{d}_{n}": require("../../{o}"),')
                    continue
                src = f"{SRC}/{b}/{d}-base-view.png" if fn is None else f"{SRC}/{b}/{fn}-{d}-view.png"
                if not os.path.exists(src): continue
                fr = np.array(Image.open(src).convert("RGBA")); m = masks[d]
                same = np.abs(fr.astype(int) - bases[d].astype(int)).max(-1) < 30
                fr[m & same, 3] = 0
                o = f"{OUT}/{b}/{it}_{d}_{n}.webp"; save(fr, o, n)
                lines.append(f'      "{d}_{n}": require("../../{o}"),')
        lines.append("    },")
    lines.append("  },")
    print(b, flush=True)
lines.append("};")
lines.append("export const WING_ROOT: Record<string, Record<string, { L?: [number, number]; R?: [number, number] }>> = " + json.dumps(meta) + ";")
open("src/ui/turnArt.ts", "w").write("\n".join(lines) + "\n")
