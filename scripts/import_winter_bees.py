"""1.7 winter bees (design/2d/winter-bees-v6, snow + gingerbread): whole concepts drawn with canonical Zhuzha's camera.
Each view is placed onto Zhuzha's canonical 1366x1151 frame (scale + offset fitted by silhouette IoU: 0.94-0.97 front,
0.90 three-quarter, 0.85 profile), its wings are cut with Zhuzha's own wing masks (bee_layers.ZDEF; in profile the masks
are grown 15% away from the wing roots, the winter wings are a bit bigger) and the layers go through the same
normalisation as scripts/import_bee_layers.py (Zhuzha's base frame as the reference). Outfits and wing roots are
Zhuzha's: same geometry. Output: assets/art/turn/<id>/ and src/ui/winterBeeArt.ts (generated).
Run: python3 scripts/import_winter_bees.py   (needs numpy)
"""
import json, os, sys
import numpy as np
from PIL import Image, ImageOps
sys.path.insert(0, os.path.dirname(__file__))
from bee_layers import ZDEF, W, OX, OY, T, S, put, poly_mask, masked

SRC = "design/2d/winter-bees-v6"
AS = "design/2d/all-species-accessories-v1"
OUT = "assets/art/turn"
BEES = {"snowbee": "snow", "gingerbee": "gingerbread"}
# canonical placement of the 1024 concept: scale, x, y (per bee, per view)
PLACE = {
    "snow": {"front": (1.281, 28, -76), "q3-front": (1.353, 12, -100), "side": (1.129, 76, -8)},
    "gingerbread": {"front": (1.290, 24, -84), "q3-front": (1.349, 6, -106), "side": (1.130, 68, -8)},
}
VIEWS = {"front": ("front", False), "q3-front": ("q3-front", False), "side": ("side", False), "q3-front-left": ("q3-front", True), "side-left": ("side", True)}
CROP = (26, 26, 486, 486); SIZES = {288: list(VIEWS), 720: ["front"]}


def grow(pts, root, k):
    return [[root[0] + (x - root[0]) * k, root[1] + (y - root[1]) * k] for x, y in pts]


def layers(src, view):
    """the zhuzha branch of bee_layers.layers() on a concept placed onto the canonical frame"""
    s, x, y = PLACE[src][view]
    con = Image.open(f"{SRC}/bee-{src}-{view}.png").convert("RGBA")
    con = con.resize((round(con.width * s), round(con.height * s)), Image.Resampling.LANCZOS)
    img = Image.new("RGBA", (1366, 1151)); img.paste(con, (x, y), con)
    anchor, sc, masks, roots = ZDEF[view]
    if view == "side":
        masks = [grow(m, roots[i], 1.15) for i, m in enumerate(masks)]
    M = T(OX, OY) @ S(sc) @ T(-anchor[0], -anchor[1])
    ba = np.array(img); out = {"wings": []}; body = Image.new("RGBA", (W, W))
    for i, pts in enumerate(masks):
        m = poly_mask(img.size, pts, 4); wl = masked(img, m)
        if view == "side" and i == 0:
            wa = np.array(wl); wa[np.array(poly_mask(img.size, masks[1])) > 0, 3] = 0; wl = Image.fromarray(wa)
        ba[np.array(m) > 0, 3] = 0
        c = Image.new("RGBA", (W, W)); put(c, wl, M); p = M @ [roots[i][0], roots[i][1], 1]
        out["wings"].append((c, (p[0], p[1])))
    put(body, Image.fromarray(ba), M)
    out["body"] = body
    return out


def bbox(a):
    ys, xs = np.nonzero(a[..., 3] > 40); return xs.min(), ys.min(), xs.max(), ys.max()


code = ["// generated by scripts/import_winter_bees.py: 1.7 winter bees (bodies and wings; outfits and wing roots are Zhuzha's)",
        "export const WINTER_TURN: Record<string, Record<string, Record<string, any>>> = {"]
for bee, src in BEES.items():
    os.makedirs(f"{OUT}/{bee}", exist_ok=True); files = {}
    def save(im, kind, d, n):
        p = f"{OUT}/{bee}/{kind}_{d}_{n}.webp"; im.save(p, "WEBP", quality=90, method=6, exact=True)
        files.setdefault(kind, []).append((f"{d}_{n}", p))
    for d, (view, mirror) in VIEWS.items():
        if mirror:
            continue  # left views share the right images (as in import_bee_layers)
        ly = layers(src, view); comp = Image.new("RGBA", (W, W))
        for wing, _ in ly["wings"]: comp.alpha_composite(wing)
        comp.alpha_composite(ly["body"])
        ref = np.array(Image.open(f"{AS}/zhuzha/{d}-base-view.png").convert("RGBA"))
        x0, y0, x1, y1 = bbox(np.array(comp)); X0, Y0, X1, Y1 = bbox(ref)
        scale = ((X1 - X0) / (x1 - x0) + (Y1 - Y0) / (y1 - y0)) / 2
        def render(im, n):
            step = (CROP[2] - CROP[0]) / n
            return im.transform((n, n), Image.Transform.AFFINE, (step / scale, 0, x0 + (CROP[0] - X0) / scale, 0, step / scale, y0 + (CROP[1] - Y0) / scale),
                                resample=Image.Resampling.BICUBIC)
        for n, dirs in SIZES.items():
            if d in dirs:
                for i, (wing, _) in enumerate(ly["wings"]): save(render(wing, n), f"w{i}", d, n)
                save(render(ly["body"], n), "base", d, n)
    for kind in ["base", "w0", "w1"]:
        for d in ["q3-front", "side"]:
            files[kind].append((f"{d}-left_288", next(p for key, p in files[kind] if key == f"{d}_288")))
    code.append(f'  "{bee}": {{')
    for kind, entries in files.items():
        code.append(f'    "{kind}": {{' + ", ".join(f'"{key}": require("../../{p}")' for key, p in entries) + "},")
    code.append("  },"); print(bee)
code.append("};")
open("src/ui/winterBeeArt.ts", "w").write("\n".join(code) + "\n")
