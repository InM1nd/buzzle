"""v1.5 bees: layered turnaround sprites per the user's 2D flight prototype (design/2d/bee-turnarounds + zhuzha-turnaround).
Per bee and view: wing layers (behind) + body. Outfits from design/2d/all-species-accessories-v1 are added on the body as
the pixels where the outfit frame differs from the plain frame. Left views are mirrors (as in the prototype).
Writes assets/art/turn/<bee>/{item}_{dir}_{size}.webp, w0_/w1_{dir}_{size}.webp and src/ui/turnArt.ts (+ WING pivots)."""
import sys, os, json, shutil, numpy as np; sys.path.insert(0, os.path.dirname(__file__))
from PIL import Image, ImageOps
from bee_layers import layers, W
AS = "design/2d/all-species-accessories-v1"; OUT = "assets/art/turn"
BEES = [s["id"] for s in json.load(open(f"{AS}/manifest.json"))["species"]]
ITEMS = {"base": None, "crown": "crown", "scarf": "scarf", "bow": "bow", "glasses": "glasses", "backpack": "bag", "wreath": "wreath", "beret": "beret", "halo": "halo"}
VIEWS = {"front": ("front", False), "q3-front": ("q3-front", False), "side": ("side", False), "q3-front-left": ("q3-front", True), "side-left": ("side", True)}
CROP = (26, 26, 486, 486); SIZES = {112: list(VIEWS), 240: ["front"]}
def bbox(a): ys, xs = np.nonzero(a[..., 3] > 40); return xs.min(), ys.min(), xs.max(), ys.max()
def save(im, o, n): im.crop(CROP).resize((n, n), Image.LANCZOS).save(o, "WEBP", quality=78, method=4)
shutil.rmtree(OUT, ignore_errors=True)
meta = {}; L = ["// generated by scripts/import_bee_layers.py — do not edit", "/* eslint-disable */", "export const TURN: Record<string, Record<string, Record<string, any>>> = {"]
for b in BEES:
    os.makedirs(f"{OUT}/{b}", exist_ok=True); meta[b] = {}; files = {}
    for d, (v, mir) in VIEWS.items():
        ly = layers(b, v); comp = Image.new("RGBA", (W, W))
        for w, _ in ly["wings"]: comp.alpha_composite(w)
        comp.alpha_composite(ly["body"])
        ref = np.array(Image.open(f"{AS}/{b}/{d}-base-view.png").convert("RGBA"))
        x0, y0, x1, y1 = bbox(np.array(comp)); X0, Y0, X1, Y1 = bbox(ref)
        s = ((X1 - X0) / (x1 - x0) + (Y1 - Y0) / (y1 - y0)) / 2
        def to512(im, flip):
            if flip: im = ImageOps.mirror(im)
            fx0 = (W - 1 - x1) if flip else x0
            return im.transform((512, 512), Image.AFFINE, (1 / s, 0, fx0 - X0 / s, 0, 1 / s, y0 - Y0 / s), resample=Image.BICUBIC)
        body = to512(ly["body"], mir)
        piv = {}
        for i, (w, (px, py)) in enumerate(ly["wings"]):
            wim = to512(w, mir); qx = ((W - 1 - px) if mir else px); fx0 = (W - 1 - x1) if mir else x0
            X = (qx - fx0) * s + X0; Y = (py - y0) * s + Y0
            piv[f"w{i}"] = [round((X - CROP[0]) / (CROP[2] - CROP[0]), 4), round((Y - CROP[1]) / (CROP[3] - CROP[1]), 4), (-1 if i == 0 else 1) * (-1 if mir else 1)]
            for n, ds in SIZES.items():
                if d in ds: o = f"{OUT}/{b}/w{i}_{d}_{n}.webp"; save(wim, o, n); files.setdefault(f"w{i}", []).append((f"{d}_{n}", o))
        meta[b][d] = piv
        for it, fn in ITEMS.items():
            src = f"{AS}/{b}/{d}-base-view.png" if fn is None else f"{AS}/{b}/{fn}-{d}-view.png"
            if not os.path.exists(src): continue
            im = body.copy()
            if fn:
                fr = np.array(Image.open(src).convert("RGBA")); diff = np.abs(fr.astype(int) - ref.astype(int)).max(-1) > 24
                ov = fr.copy(); ov[~diff, 3] = 0; im.alpha_composite(Image.fromarray(ov))
            for n, ds in SIZES.items():
                if d in ds: o = f"{OUT}/{b}/{it}_{d}_{n}.webp"; save(im, o, n); files.setdefault(it, []).append((f"{d}_{n}", o))
    L.append(f'  "{b}": {{')
    for k, lst in files.items():
        L.append(f'    "{k}": {{' + ", ".join(f'"{key}": require("../../{o}")' for key, o in lst) + "},")
    L.append("  },"); print(b, flush=True)
L.append("};")
L.append("/** wing pivots in frame fractions [x, y, flap sign] per view: w0/w1 */")
L.append("export const WING_ROOT: Record<string, Record<string, Record<string, [number, number, number]>>> = " + json.dumps(meta) + ";")
open("src/ui/turnArt.ts", "w").write("\n".join(L) + "\n")
